const PI = Math.PI;
const mul = (A, B) => A.map((r) => [0, 1, 2].map((j) => r[0] * B[0][j] + r[1] * B[1][j] + r[2] * B[2][j]));
const Rz = (a) => [[Math.cos(a), -Math.sin(a), 0], [Math.sin(a), Math.cos(a), 0], [0, 0, 1]];
const Rx = (a) => [[1, 0, 0], [0, Math.cos(a), -Math.sin(a)], [0, Math.sin(a), Math.cos(a)]];
const hinge = (th, rho) => mul(mul(Rz(th), Rx(rho)), Rz(-th));
const HOLD = 0.14; // the paper first turns on the table, folding starts after this
const ease = (x) => { const c = Math.min(1, Math.max(0, x)); return c * c * (3 - 2 * c); };

/** fold angles of the 8 creases at progress t (0..1) */
export function fanAngles(t) {
  const x = ease((t - HOLD) / (1 - HOLD)) * (FAN.length - 1);
  const i = Math.min(FAN.length - 2, Math.floor(x));
  const f = x - i;
  return FAN[i].map((v, k) => v + (FAN[i + 1][k] - v) * f);
}
/** rotation matrix per sector (0..7) for the given crease angles */
export function fanMatrices(rho) {
  const out = [[[1, 0, 0], [0, 1, 0], [0, 0, 1]]];
  for (let k = 1; k < 8; k++) out.push(mul(out[k - 1], hinge((k * PI) / 4, rho[k])));
  return out;
}
const apply = (M, p) => [0, 1, 2].map((i) => M[i][0] * p[0] + M[i][1] * p[1] + M[i][2] * p[2]);
const sectorOf = (x, y) => { let a = Math.atan2(y, x); if (a < 0) a += 2 * PI; return Math.min(7, Math.floor((a + 1e-9) / (PI / 4))); };

const smooth = (x) => { const c = Math.min(1, Math.max(0, x)); return c * c * (3 - 2 * c); };
/** the folded paper at progress t, held symmetric about the diagonal through the corner that stays on the table */
function fanRaw(t, faces) {
  const rho = fanAngles(t);
  const Ms = fanMatrices(rho);
  // while the paper lies flat in several layers, give every layer a hair of height so that they do not flicker:
  // a layer sits above the one it is folded from when the fold is a valley, below it when it is a mountain
  const h = [0];
  for (let k = 1; k < 8; k++) h.push(h[k - 1] + 0.6 * Ms[k - 1][2][2] * Math.sign(rho[k]) * Math.sin(Math.abs(rho[k]) / 2) ** 2);
  const base = faces.map((f) => {
    const c = f.P.reduce((a, p) => [a[0] + p[0] / f.P.length, a[1] + p[1] / f.P.length], [0, 0]);
    const k = sectorOf(c[0], c[1]);
    return f.P.map((p) => { const q = apply(Ms[k], p); return [q[0], q[1], q[2] + h[k]]; });
  });
  let zmin = Infinity;
  for (const P of base) for (const p of P) zmin = Math.min(zmin, p[2]);
  return base.map((P) => P.map((p) => [p[0], p[1], p[2] - zmin]));
}
const rotZ = (a, p) => [p[0] * Math.cos(a) - p[1] * Math.sin(a), p[0] * Math.sin(a) + p[1] * Math.cos(a), p[2]];
/** custom pose function for buildOp: faces must be the eight triangles around the centre of the paper.
 *  The paper first turns on the table until a corner points at you (like in the video), then collapses; the
 *  stack that comes out is centred in the picture. */
export function fanPose(t, faces) {
  const c = fanCornerEnd(1);
  const psi = -PI / 2 - Math.atan2(c[1], c[0]); // turn that leaves the finished stack upright
  const end = fanRaw(1, faces).map((P) => P.map((p) => rotZ(psi, p)));
  const xs = end.flat().map((p) => p[0]), ys = end.flat().map((p) => p[1]);
  const shift = [-(Math.min(...xs) + Math.max(...xs)) / 2, -(Math.min(...ys) + Math.max(...ys)) / 2];
  const a = psi * smooth(t / HOLD), sh = smooth((t - 0.45) / 0.5);
  return fanRaw(t, faces).map((P) => P.map((p) => { const q = rotZ(a, p); return [q[0] + shift[0] * sh, q[1] + shift[1] * sh, q[2]]; }));
}
